import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const templateRoot = resolve(root, "packages/cli/templates/github");
const output = resolve(root, "packages/cli/src/generated-assets.ts");
const files = [
  "lore-codex-review.yml",
  "lore-devin-review.yml",
  "lore-observe-correction.yml",
  "review-output.schema.json",
];

const entries = await Promise.all(
  files.map(async (file) => [file, await readFile(resolve(templateRoot, file), "utf8")]),
);
const source = `// Generated by scripts/generate-cli-assets.mjs. Do not edit directly.
export const GITHUB_TEMPLATE_ASSETS = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;
`;

await writeFile(output, source, "utf8");
